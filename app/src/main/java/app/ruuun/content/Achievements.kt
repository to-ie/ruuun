    val id: String,
    val title: String,
    val category: BadgeCategory,
    val metric: BadgeMetric,
    val threshold: Int,
    val hint: String,
    /** Word used when showing "12 / 15 days" style progress. */
    val unit: String,
) {
    val secret: Boolean get() = category == BadgeCategory.SECRET
}

