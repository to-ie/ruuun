    LOGS_AT_MOST_500M,
    MAX_DAYS_IN_ANY_WEEK,
    MAX_NOTED_LOGS_IN_WEEK,
    MAX_SESSION_M,
    MET_TARGET_LOGS,
    MODE_WALK_JOG,
    MODE_WALK_ONLY,
    NOTED_LOGS,
    QUEST_COMPLETIONS,
    RUNS_IN_MONTH_01,
    RUNS_IN_MONTH_02,
    RUNS_IN_MONTH_03,
    RUNS_IN_MONTH_04,
    RUNS_IN_MONTH_05,
    RUNS_IN_MONTH_06,
    RUNS_IN_MONTH_07,
    RUNS_IN_MONTH_08,
    RUNS_IN_MONTH_09,
    RUNS_IN_MONTH_10,
    RUNS_IN_MONTH_11,
    RUNS_IN_MONTH_12,
    RUN_DAYS,
    RUN_LOGS_WITH_EFFORT,
    TAG_FAMILY,
    TAG_NATURE,
    TAG_NEW_ROUTE,
    TAG_PARK,
    TOTAL_M,
    WEEKS_MET,
}

data class BadgeDef(
    val id: String,
    val title: String,
    val category: BadgeCategory,
    val metric: BadgeMetric,
    val threshold: Int,
    val hint: String,
    /** Word used when showing "12 / 15 days" style progress. */
    val unit: String,
) {
    val secret: Boolean get() = category == BadgeCategory.SECRET
}

