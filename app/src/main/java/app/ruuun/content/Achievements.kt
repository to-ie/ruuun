package app.ruuun.content

/**
 * The 141-badge seed catalogue from the build handoff, Appendix A.
 *
 * Every rule is a typed `metric >= threshold` comparison against a
 * [app.ruuun.logic.StatsSnapshot]; nothing is parsed from text at runtime. Badges are
 * recalculated from the current logs each time, so correcting data can lock one again.
 */

/** Display grouping. One icon and colour per category, never one per badge. */
enum class BadgeCategory(val title: String) {
    FIRST_STEPS("First steps"),
    RUN_DAYS("Run days"),
    BEST_OUTING("Best single outing"),
    TOTAL_DISTANCE("Total distance"),
    WEEKLY("Weekly"),
    ADVENTURE("Adventure"),
    REFLECTION("Reflection"),
    STORY("Story"),
    QUESTS("Quests"),
    SEASONS("Seasons"),
    SECRET("Secret"),
}

/**
 * A countable fact derived from the logs. `ALL_THREE_EFFORTS_RECORDED` is a 0/1
 * metric so that every badge can use the same `>= threshold` comparison.
